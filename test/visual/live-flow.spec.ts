// AI-01 live-mode browser tests. The app runs in Anthropic mode with the real SDK path, pointed at the local fake
// upstream (test/support/fake-anthropic.mjs). These prove wiring, copy, safety and recovery — NOT model quality;
// no response here is a genuine model output.
const FAKE = "http://127.0.0.1:3199";
const EVIDENCE = "docs/evidence/ai-01/screenshots";
mkdirSync(EVIDENCE, { recursive: true });
const btn = (page: Page, name: string) => page.getByRole("button", { name, exact: true });
const pick = (page: Page, name: string) => page.locator(".message", { hasText: name }).click();
const csv = (rows: [string, string, string, string][]) =>
  Buffer.from(["id,candidate_name,subject,message", ...rows.map((r) => r.map((c) => `"${c.replace(/"/g, '""')}"`).join(","))].join("\r\n"));

async function importCsv(page: Page, rows: [string, string, string, string][]) {
  await page.goto("/");
  page.on("dialog", (d) => d.accept());
  await page.setInputFiles("#csvFile", { name: "live.csv", mimeType: "text/csv", buffer: csv(rows) });
  await btn(page, `Process ${rows.length} valid messages →`).click();
}
async function processAll(page: Page, rows: [string, string, string, string][]) {
  await importCsv(page, rows);
  await btn(page, "Start AI processing →").click();
  await expect(page.locator("#pageTitle")).toHaveText("Inbox & human review", { timeout: 30_000 });
}
const fakeCalls = async (page: Page) => (await (await page.request.get(`${FAKE}/__calls`)).json()) as { model: string; max_tokens: number; thinking: unknown; format: string; sampling: string[]; marker: string }[];

