test("end-to-end: fixture-id collision goes to the provider; edit, approve, Results and downloaded CSV are accurate", async ({ page }) => {
  // M003 is a canned fixture id (hire-claim fixture); the content differs, so it must never reuse fixture output.
  await processAll(page, [["M003", "Sarah James", "Interview link", "My interview link doesn't work. Can you help?"]]);
  const calls = await fakeCalls(page);
  expect(calls).toHaveLength(1);
  expect(calls[0]).toMatchObject({ model: "claude-haiku-5-5", max_tokens: 1600, thinking: { type: "disabled" }, format: "json_schema", sampling: [] });
  const editor = page.locator("#draftEditor");
  await expect(editor).toHaveValue(/fake upstream draft/);
  await expect(page.locator("body")).not.toContainText("offer letter is being prepared");
  await expect(page.locator("#aiProvenance")).toHaveText("Generated by Anthropic · claude-haiku-5-5 · suggestion for recruiter review only");
  await editor.fill("Hi Sarah, thanks for flagging the link. The recruitment team will send a working link.");
  await btn(page, "Approve draft").click();
  expect(await page.locator("#inbox-view").innerText()).not.toMatch(/mock|simulat/i);
  await page.click("#nav-results");
  expect(await page.locator("#results-view").innerText()).not.toMatch(/mock|simulat/i);
  await expect(page.locator("#results-view tbody tr td").nth(3)).toHaveText("Approved");
  const [dl] = await Promise.all([page.waitForEvent("download"), btn(page, "Download CSV results").click()]);
  const text = readFileSync((await dl.path())!, "utf8");
  expect(text).toContain('"Approved"');
  expect(text).toContain("fake upstream draft"); // original AI draft column
  expect(text).toContain("The recruitment team will send a working link."); // reviewed draft column
  await expect(page.locator("#results-view .notice.warn").last()).toContainText("AI drafts are Anthropic-generated suggestions, not official messages");
});

