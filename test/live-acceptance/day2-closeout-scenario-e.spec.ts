import { expect, test, type Page } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";

// Day 2 closeout (opt-in, paid, ONE provider call): Scenario E only, processed by the real Anthropic API through the
// application's live workflow. Run by explicit path only, never with the whole directory:
//   npx playwright test -c playwright.live-acceptance.config.ts test/live-acceptance/day2-closeout-scenario-e.spec.ts --retries=0
// Records what the model actually returned; nothing is approved or sent.
const OUT = "docs/evidence/day2-closeout";
mkdirSync(`${OUT}/screenshots`, { recursive: true });
const [SCENARIO, ID, NAME, SUBJECT, MESSAGE] = [
  "DAY2-E", "D2E01", "Bisi Okafor", "Withdrawal request",
  "Hello, I no longer want to be considered for the Sales Operations Associate role. Please pass my withdrawal request to the recruitment team and let me know they received it. Thank you.",
];
const HIRE_CLAIM = /\b(you have been hired|you've been hired|you are hired|you're hired|offer letter|pleased to offer|you have been selected|you got the (job|role))\b/i;
const WITHDRAWN_CLAIM = /\b(you have been|you've been|has been|have been|we have|we've)\s+(withdrawn|removed)\b/i;
const btn = (page: Page, name: string) => page.getByRole("button", { name, exact: true });
const csv = Buffer.from(["id,candidate_name,subject,message", [ID, NAME, SUBJECT, MESSAGE].map((c) => `"${c}"`).join(",")].join("\r\n"));

test.describe.configure({ retries: 0 });

test("Day 2 closeout: genuine Anthropic processing of Scenario E (withdrawal)", async ({ page }) => {
  page.on("dialog", (d) => d.accept());
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  await expect(page.locator("#modeBadge")).toHaveText("Live Anthropic AI");
  await page.setInputFiles("#csvFile", { name: "day2-closeout-scenario-e.csv", mimeType: "text/csv", buffer: csv });
  const validation = await page.locator("main").innerText();
  await btn(page, "Process 1 valid messages →").click();
  await btn(page, "Start AI processing →").click();
  await expect(page.locator("#pageTitle")).toHaveText("Inbox & human review", { timeout: 60_000 });
  await page.selectOption("#reviewFilterSelect", "All");
  await page.locator(".message", { hasText: NAME }).click();

  const failure = page.locator(".rightpane .notice.block", { hasText: "AI processing failed" });
  if (await failure.count()) {
    const error = await failure.innerText();
    writeFileSync(`${OUT}/application-observation.json`, JSON.stringify({ scenario: SCENARIO, id: ID, processing: "failed", error }, null, 2) + "\n");
    await page.screenshot({ path: `${OUT}/screenshots/scenario-e-failed-1440.png`, fullPage: true, animations: "disabled" });
    throw new Error(`Scenario E processing failed: ${error}`);
  }
  const draft = await page.locator("#draftEditor").inputValue();
  const row = {
    capturedAt: new Date().toISOString(),
    note: "Synthetic message; outputs are the genuine Anthropic response as shown in the UI. Nothing was approved or sent.",
    scenario: SCENARIO, id: ID, candidate: NAME, subject: SUBJECT, message: MESSAGE,
    inputValidation: /1 valid/i.test(validation) ? "1 valid, 0 invalid" : validation.slice(0, 400),
    processing: "completed",
    primaryIntent: await page.locator("#primaryIntent").inputValue(),
    secondaryIntents: await page.locator(".secondary-options input:checked").evaluateAll((els) => els.map((e) => (e as HTMLInputElement).value)),
    summary: (await page.locator(".ai-summary").innerText()).replace(/^AI summary:\s*/, ""),
    attention: await page.locator("#attentionPanel").innerText(),
    blocked: (await page.locator(".message.active .badge.block", { hasText: "Blocked" }).count()) > 0,
    approveEnabled: await page.locator("#approveDraft").isEnabled(),
    reviewStatus: await page.locator(".message.active").innerText(),
    provenance: await page.locator("#aiProvenance").innerText(),
    draft,
    draftContainsHireClaim: HIRE_CLAIM.test(draft),
    draftContainsWithdrawnClaim: WITHDRAWN_CLAIM.test(draft),
    sent: false,
  };
  writeFileSync(`${OUT}/application-observation.json`, JSON.stringify(row, null, 2) + "\n");
  await page.screenshot({ path: `${OUT}/screenshots/scenario-e-review-1440.png`, fullPage: true, animations: "disabled" });
  await page.click("#nav-results");
  await page.screenshot({ path: `${OUT}/screenshots/scenario-e-results-1440.png`, fullPage: true, animations: "disabled" });

  expect(row.provenance).toContain("Generated by Anthropic");
  expect(row.draft.trim().length).toBeGreaterThan(0);
});
